/**
 * @file Model.h
 * @brief Абстрактный базовый класс математической модели объекта управления.
 *
 * Иерархия моделей перенесена из лабораторной работы №1 (вариант 6):
 * линейная модель 1.6, нелинейная модель 2.8 и дифференциальное
 * уравнение 3.10. Все модели используются как объекты управления (Plant)
 * в замкнутом контуре «ПИД-регулятор + объект».
 */
#pragma once

/**
 * @brief Интерфейс дискретной модели объекта управления.
 *
 * Каждая модель по текущему состоянию и управляющему воздействию
 * вычисляет следующее значение регулируемой величины.
 */
class Model
{
public:
    /// Виртуальный деструктор для корректного удаления через указатель базового типа.
    virtual ~Model() = default;

    /**
     * @brief Вычисляет следующее значение выхода модели.
     * @param y      текущее значение y(t)
     * @param yPrev  предыдущее значение y(t-1)
     * @param yPrev2 значение y(t-2)
     * @param u      управляющее воздействие u(t)
     * @param dt     шаг интегрирования (используется моделью 3.10)
     * @return значение y(t+1)
     */
    virtual double calculateNext(
        double y,
        double yPrev,
        double yPrev2,
        double u,
        double dt
    ) const = 0;

    /// Человекочитаемое имя модели.
    virtual const char* getName() const = 0;
};
